"""Write rust/core/examples/ct_dudect/data.rs: the constants the exact-Gaussian and garbling targets of the
timing harness need from the Python reference (a FACCT table for sigma = 1000, a wide one for the width of the
standard tMCFE, a CIRC v1 circuit of pyfe4ai.circuits). Run from the repository:
    python tools/gen_ct_data.py rust/core/examples/ct_dudect/data.rs
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # the tree, as tools/gen_site_matrix.py

import gmpy2 as gp  # noqa: E402

from pyfe4ai.circuits import library  # noqa: E402
from pyfe4ai.primitives import garbling  # noqa: E402
from pyfe4ai.primitives import sampling as su  # noqa: E402

out = sys.argv[1]
sigma = gp.mpq(1000)
params = su._facct_params(sigma)
mant, exp = params.neg_c.as_mantissa_exp()
mant, exp = -int(mant), int(exp)
shift = mant.bit_length() - 128
mant = mant >> shift if shift > 0 else mant << -shift
# the wide kernel (rust/core/src/facct_wide.rs): the width 'tmcfe_std' of tests/sampling/test_native_facct_wide.py
wide_sigma = gp.mpq(447376781648190700506077024983381091686950567609395922862080)
wide = su._facct_params(wide_sigma)
wmant, wexp = wide.neg_c.as_mantissa_exp()
wmant, wexp = -int(wmant), int(wexp)
wshift = wmant.bit_length() - 128
wmant = wmant >> wshift if wshift > 0 else wmant << -wshift
wk = [(wide.k >> (64 * i)) & (2 ** 64 - 1) for i in range(8)]
assert wide.k < 2 ** 448 and wide.k > 2 ** 50
circ = library.linear_threshold(4, 4, 4)
enc = circ.circuit.encode()
parsed = garbling.parse_circuit(enc)
lines = [
    "// Generated by tools/gen_ct_data.py from the Python reference; do not edit.",
    "// FACCT table of sigma = 1000 (pyfe4ai.primitives.sampling._facct_params, as backend.native_impl._facct_table).",
    "pub const FACCT_K: u64 = {};".format(params.k),
    "pub const FACCT_Y_BITS: u32 = {};".format(params.y_bits),
    "pub const FACCT_CDT: [&str; {}] = [{}];".format(len(params.cdt), ", ".join('"{}"'.format(int(c)) for c in params.cdt)),
    "pub const FACCT_C_MANT: u128 = {};".format(mant),
    "pub const FACCT_C_EXP: i32 = {};".format(exp + shift),
    "// FACCT table of the wide kernel for sigma = {} (tMCFE standard; backend.native_impl._facct_wide_table).".format(int(wide_sigma)),
    "pub const FACCT_WIDE_K: [u64; 8] = [{}];".format(", ".join(str(w) for w in wk)),
    "pub const FACCT_WIDE_Y_BITS: u32 = {};".format(wide.y_bits),
    "pub const FACCT_WIDE_CDT: [&str; {}] = [{}];".format(len(wide.cdt), ", ".join('"{}"'.format(int(c)) for c in wide.cdt)),
    "pub const FACCT_WIDE_C_MANT: u128 = {};".format(wmant),
    "pub const FACCT_WIDE_C_EXP: i32 = {};".format(wexp + wshift),
    "// CIRC v1 encoding of pyfe4ai.circuits.library.linear_threshold(4, 4, 4): m key wires, n data wires.",
    "pub const CIRCUIT: &[u8] = &[{}];".format(", ".join(str(b) for b in enc)),
    "pub const CIRCUIT_M: usize = {};".format(parsed.m),
    "pub const CIRCUIT_N: usize = {};".format(parsed.n),
]
open(out, "w").write("\n".join(lines) + "\n")
print("k", params.k, "y_bits", params.y_bits, "wide k bits", wide.k.bit_length(), "wide y_bits", wide.y_bits, "cdt", len(params.cdt), "circuit bytes", len(enc), "m", parsed.m, "n", parsed.n)
